#!/usr/bin/env python3
"""Render the exact trusted Comparator statement for either track."""

from __future__ import annotations

import sys

from benchmark_contract import (
    atomic_write_text,
    parse_centibits,
    parse_radius,
    parse_unsafe_index,
    split_track,
)


def main() -> None:
    if len(sys.argv) != 5:
        raise SystemExit(
            "usage: render-benchmark-challenge.py "
            "half-lower|half-upper|quarter-lower|quarter-upper CENTIBITS CLAIM OUTPUT"
        )

    track, raw_score, claim, output = sys.argv[1:]
    rate, profile = split_track(track)
    module_prefix = "Quarter" if rate == "quarter" else ""
    ns = "ProximityPrize.Benchmark" + (".Quarter" if rate == "quarter" else "")
    try:
        centibits = parse_centibits(raw_score)
        if profile == "lower":
            numerator, denominator = parse_radius(claim)
            source = f"""
/- Generated by scripts/render-benchmark-challenge.py. Do not edit. -/
import ProximityPrize.Benchmark.{module_prefix}TargetLower

namespace {ns}

theorem candidate : ProtocolClaim {centibits} {numerator} {denominator} := by
  sorry

end {ns}
""".lstrip()
        else:
            unsafe_index = parse_unsafe_index(claim, profile=rate)
            source = f"""
/- Generated by scripts/render-benchmark-challenge.py. Do not edit. -/
import ProximityPrize.Benchmark.{module_prefix}TargetUpper

namespace {ns}.Upper

theorem candidate : ProtocolClaimUpper {centibits} {unsafe_index} := by
  sorry

end {ns}.Upper
""".lstrip()
    except (OSError, ValueError) as error:
        raise SystemExit(str(error)) from error

    atomic_write_text(output, source)


if __name__ == "__main__":
    main()
